// Writes web/out/_redirects after `next build` (decisions D-35, D-36).
// Firebase builds: proxy Google sign-in's /__/auth/* and /__/firebase/init.json to <project>.firebaseapp.com
// (status 200, forced), so authDomain can be the app's own domain. Demo builds: no proxy.
import { writeFileSync } from "node:fs";

const project = (process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID ?? "").trim();
const lines = ["# Generated by web/scripts/postbuild.mjs"];
if (project) {
  lines.push(`/__/auth/*  https://${project}.firebaseapp.com/__/auth/:splat  200!`);
  lines.push(`/__/firebase/init.json  https://${project}.firebaseapp.com/__/firebase/init.json  200!`);
}
writeFileSync(new URL("../out/_redirects", import.meta.url), lines.join("\n") + "\n");
console.log(project ? `_redirects: Google sign-in proxy to ${project}.firebaseapp.com` : "_redirects: demo build, no auth proxy");
