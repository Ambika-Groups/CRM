// Writes web/out/_redirects after `next build` (decisions D-35, D-36).
// Firebase builds: proxy Google sign-in's /__/auth/* and /__/firebase/init.json to <project>.firebaseapp.com
// (status 200, forced), so authDomain can be the app's own domain. Demo builds: no proxy.
import { readFileSync, writeFileSync } from "node:fs";

// Next reads web/.env.local for the build; this script is plain Node, so it reads the one variable it needs the same way
// (a variable set in the environment, even to nothing, wins, as in Next; Netlify sets them in the environment).
let project = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID;
if (project === undefined) {
  try {
    const line = readFileSync(new URL("../.env.local", import.meta.url), "utf8").split(/\r?\n/).find((l) => l.startsWith("NEXT_PUBLIC_FIREBASE_PROJECT_ID="));
    project = line ? line.slice(line.indexOf("=") + 1) : "";
  } catch { project = ""; }
}
project = (project ?? "").trim();
const lines = ["# Generated by web/scripts/postbuild.mjs"];
if (project) {
  lines.push(`/__/auth/*  https://${project}.firebaseapp.com/__/auth/:splat  200!`);
  lines.push(`/__/firebase/init.json  https://${project}.firebaseapp.com/__/firebase/init.json  200!`);
}
writeFileSync(new URL(`../${process.env.AG_OUT_DIR || "out"}/_redirects`, import.meta.url), lines.join("\n") + "\n");
console.log(project ? `_redirects: Google sign-in proxy to ${project}.firebaseapp.com` : "_redirects: demo build, no auth proxy");
