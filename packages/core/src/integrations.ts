/** One Test's outcome: Pass or Fail, one plain sentence, and what to do when it fails. */
export interface TestOutcome { ok: boolean; message: string; hint?: string }

/** What a super user's page may read about one integration (`integrations/{id}`): never a secret. */
export interface IntegrationStatus {
  id: IntegrationId;
  enabled: boolean;
  /** Public values, by field key. */
  values: Record<string, string>;
  /** Secret fields that have a value, with the masked tail. */
  masked: Record<string, string>;
  enforce?: boolean;
  /** The last Test result. Cleared when the settings change, so "verified" never outlives a change. */
  test?: (TestOutcome & { at: string }) | null;
  /** The last time a Test passed, kept even after a later failure. */
  lastOkAt?: string | null;
  updatedAt?: string;
  updatedBy?: string;
}

/** "••••1234": enough to recognise a key, never enough to use it. */
export function maskSecret(v: string): string {
  const tail = v.length >= 12 ? v.slice(-4) : "";
  return `••••${tail}`;
}

/** "7 of 10 verified": items whose latest Test passed, out of the items that count. */
export function verifiedSummary(statuses: Partial<Record<IntegrationId, IntegrationStatus | null>>): { verified: number; total: number } {
  const counted = INTEGRATION_IDS.filter((id) => INTEGRATIONS[id].counts);
  return { verified: counted.filter((id) => statuses[id]?.test?.ok === true && statuses[id]?.enabled !== false).length, total: counted.length };
}

export const SETUP_REAUTH_SECONDS = 300;

/** True when the person signed in within the last 5 minutes (`authTime` is the token's auth_time, in seconds). */
export function signedInRecently(authTimeSeconds: number | undefined, nowMs: number): boolean {
  return typeof authTimeSeconds === "number" && nowMs / 1000 - authTimeSeconds <= SETUP_REAUTH_SECONDS;
}

/**
 * Checks values for an integration before saving. A blank secret keeps the saved one (`hasSecret`), so changing the
 * from-address doesn't need the key again. Returns field key → message; empty when fine.
 */
export function validateIntegration(def: IntegrationDef, values: Record<string, string>, hasSecret: Record<string, boolean>): Record<string, string> {
  const errors: Record<string, string> = {};
  for (const f of def.fields) {
    const v = (values[f.key] ?? "").trim();
    if (!v) {
      if (f.required && !(f.secret && hasSecret[f.key])) errors[f.key] = "This is needed.";
      continue;
    }
    if (f.pattern && !new RegExp(f.pattern).test(v)) errors[f.key] = f.patternMessage ?? "This doesn't look right.";
    if (v.length > 500) errors[f.key] = "This is too long.";
  }
  const unknown = Object.keys(values).filter((k) => !def.fields.some((f) => f.key === k));
  for (const k of unknown) errors[k] = "This isn't a setting.";
  return errors;
}

// ---------- the Firebase web config (item 1) ----------

export type FirebaseWebConfig = Record<"apiKey" | "authDomain" | "projectId" | "storageBucket" | "messagingSenderId" | "appId", string>;

const CONFIG_KEYS = ["apiKey", "authDomain", "projectId", "storageBucket", "messagingSenderId", "appId"] as const;
const ENV_NAMES: Record<(typeof CONFIG_KEYS)[number], string> = {
  apiKey: "NEXT_PUBLIC_FIREBASE_API_KEY", authDomain: "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN", projectId: "NEXT_PUBLIC_FIREBASE_PROJECT_ID",
  storageBucket: "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET", messagingSenderId: "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID", appId: "NEXT_PUBLIC_FIREBASE_APP_ID",
};

/**
 * Reads the config out of whatever was pasted: the snippet the Firebase console shows (`const firebaseConfig = { ... }`),
 * JSON, or NEXT_PUBLIC_FIREBASE_* lines. Returns only the six values it found; the form then validates them.
 */
export function parseFirebaseConfigBlock(text: string): Partial<FirebaseWebConfig> {
  const out: Partial<FirebaseWebConfig> = {};
  for (const k of CONFIG_KEYS) {
    const env = new RegExp(`${ENV_NAMES[k]}\\s*=\\s*["']?([^"'\\s]+)["']?`).exec(text);
    const obj = new RegExp(`["']?${k}["']?\\s*:\\s*["']([^"']+)["']`).exec(text);
    const v = env?.[1] ?? obj?.[1];
    if (v) out[k] = v.trim();
  }
  return out;
}

/** The exact lines to paste under Netlify's Environment variables, so every device gets the same connection. */
export function firebaseConfigToEnv(cfg: Partial<FirebaseWebConfig>): string {
  return CONFIG_KEYS.map((k) => `${ENV_NAMES[k]}=${cfg[k] ?? ""}`).join("\n");
}

/** Field messages for a web config, in the same plain words as the page. */
export function validateFirebaseConfig(cfg: Partial<FirebaseWebConfig>): Record<string, string> {
  return validateIntegration(INTEGRATIONS.firebaseConfig, Object.fromEntries(CONFIG_KEYS.map((k) => [k, cfg[k] ?? ""])), {});
}
