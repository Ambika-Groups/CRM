/**
 * Setup & integrations (D-48, D-49): every service the CRM connects to, what each needs, and how it is tested.
 * Shared by the page, the callables and the tests. Secret values are write-only: saved by a callable into a
 * server-only document, never read back by a client; what a client may read is the status, a masked tail
 * ("••••1234") and the public values. Each item has its own Test, with a Pass or Fail, one plain sentence and a hint.
 */

export const INTEGRATION_IDS = [
  "firebaseConfig", "firestore", "storage", "storageR2", "storageCloudinary", "storageFirebase", "signIn", "functions", "appCheck", "push", "email", "websiteLink", "maps", "whatsapp",
] as const;
export type IntegrationId = (typeof INTEGRATION_IDS)[number];

/**
 * Where an item's values live:
 *  - "device": the browser's own storage (the Firebase web config is needed before anything can connect, so it can't
 *    be in the database; Netlify's variables stay the source of truth for everyone, D-36);
 *  - "stored": saved by a callable into the database (public values) and the server-only secret store (secrets);
 *  - "check": nothing to type in; the page only tests and reports.
 */
export type IntegrationKind = "device" | "stored" | "check";

export interface IntegrationField {
  key: string;
  /** Secret fields are write-only; public ones may be read by the client. */
  secret: boolean;
  required: boolean;
  /** The value must match this (a gentle format check; the Test button does the real one). */
  pattern?: string;
  /** Plain-words message when the pattern fails. */
  patternMessage?: string;
}

export interface IntegrationDef {
  id: IntegrationId;
  kind: IntegrationKind;
  fields: IntegrationField[];
  /** False while the service has no feature to use it (WhatsApp, Phase 4): shown, disabled, "Coming in a later phase". */
  available: boolean;
  /** Counts toward "N of M verified". Optional services still count; unavailable ones do not. */
  counts: boolean;
  /** Has an "enforce" switch (App Check). */
  hasEnforce?: boolean;
  /** The key is generated by the server and shown once (website link). */
  generated?: boolean;
  /** Where the test runs: in the browser, or on the server. */
  testsIn: "browser" | "server";
}

